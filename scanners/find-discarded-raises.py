#!/usr/bin/env python3
"""Find assertRaises / pytest.raises calls whose result is thrown away.

`self.assertRaises(ValueError)` returns a context manager. Used as a bare
statement it is built, discarded, and nothing is ever checked, so the test
passes no matter what the code does. The callable form
`self.assertRaises(ValueError, f, x)` and the `with` form are both fine.

Parsed with `ast`, not regex, so the "is this a bare statement" question is
answered by the tree: a `with` puts the call in `With.items[].context_expr`
and an assignment puts it in `Assign.value`, while a discarded one is an
`Expr`. Nothing else can look like that.

Reported shapes:
  self.assertRaises(E)                 1 arg, so not the callable form
  self.assertRaisesRegex(E, "pat")     2 args, same
  pytest.raises(E)                     bare, so not a with-block
  m.assert_called_once                 named but never called

The last one is the same defect through a different mechanism: naming a mock's
assertion without parentheses is an attribute access that returns the bound
method and drops it. With the parentheses that line raises
`AssertionError: Expected 'mock' to have been called once. Called 0 times.`, so
two characters separate a working assertion from a no-op.

A MISSPELLED mock assertion is deliberately not looked for, because Mock guards
those itself: `m.assert_caled_once_with(1)` raises
`AttributeError: 'assert_caled_once_with' is not a valid assertion`.
"""
import argparse
import ast
import re
import pathlib
import sys
import warnings

# Suppress the SCANNED repository's SyntaxWarnings. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is the subject's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path.
# changedetection.io alone emitted twelve lines of it, which buried this
# scanner's actual result. A scanner must not report its subject's warnings as
# if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)


# A generated file is not a place to find a bug: the defect, if any, is in the
# generator's input, and a PR against the output is rejected on sight. ccxt
# transpiles its Python test suite from TypeScript and every file says
# "PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN",
# which is how 18 candidates there turned out to be unfilable.
GENERATED_BANNER = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')


def is_generated(text):
    """True when the file announces itself as generated, judged on its head."""
    return bool(GENERATED_BANNER.search(text[:4000]))

# name -> smallest number of positional args the CALLABLE form needs
UNITTEST = {
    'assertRaises': 2,
    'assertRaisesRegex': 3,
    'assertRaisesRegexp': 3,
    'assertWarns': 2,
    'assertWarnsRegex': 3,
    'assertDoesNotWarn': 2,
    # assertLogs and assertNoLogs have NO callable form at all, so any bare
    # call discards the manager. A sentinel bigger than any argument count
    # expresses that without a second code path.
    'assertLogs': 1 << 30,
    'assertNoLogs': 1 << 30,
}
# Same idea for pytest's legacy callable forms, which do NOT share an arity.
# `raises(E, func, ...)` and `warns(W, func, ...)` take the expected type first,
# so the callable form needs 2. `deprecated_call(func, ...)` takes no expected
# type at all, so ONE positional argument is already the callable form.
# click-default-group's test.py:78 is `pytest.deprecated_call(cli.command,
# default=True)`, which runs and asserts; treating it as needing 2 reported a
# live test as dead.
PYTEST = {
    'pytest.raises': 2,
    'pytest.warns': 2,
    'pytest.deprecated_call': 1,
}
SKIP_DIRS = {'.git', '.tox', '.venv', 'venv', 'node_modules', 'build', 'dist',
             '.mypy_cache', '.pytest_cache', 'site-packages', '__pycache__',
             '.pixi', '.conda', '.eggs'}


# Real unittest.mock assertion methods, as a whitelist rather than an
# `assert_` prefix match, so a project's own attribute that happens to start
# with assert_ is not reported as a mock assertion.
MOCK_ASSERTIONS = {
    'assert_called', 'assert_called_once', 'assert_called_with',
    'assert_called_once_with', 'assert_any_call', 'assert_has_calls',
    'assert_not_called',
    'assert_awaited', 'assert_awaited_once', 'assert_awaited_with',
    'assert_awaited_once_with', 'assert_any_await', 'assert_has_awaits',
    'assert_not_awaited',
}


def call_name(node):
    """Dotted-ish name for a Call's func, or None."""
    f = node.func
    if isinstance(f, ast.Attribute):
        if isinstance(f.value, ast.Name):
            return f'{f.value.id}.{f.attr}'
        return f.attr
    if isinstance(f, ast.Name):
        return f.id
    return None


def expected_failure_ranges(tree):
    """Line ranges of `with <raises-family>(...):` bodies.

    A discarded raises-call inside one is deliberate: it is the thing being
    asserted about. cpython's own Lib/test/test_unittest/test_case.py does
    exactly this 24 times, as in

        with self.assertRaises(TypeError):
            self.assertRaises()

    which checks that misuse is rejected. Counting those as defects would make
    the tool useless on any test suite that tests its own assert helpers.
    """
    ranges = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.With, ast.AsyncWith)):
            continue
        for item in node.items:
            ctx = item.context_expr
            if not isinstance(ctx, ast.Call):
                continue
            name = call_name(ctx)
            if name and name.rsplit('.', 1)[-1] in (
                    set(UNITTEST) | {'raises', 'warns', 'deprecated_call'}):
                body_lines = [n.lineno for n in ast.walk(node)
                              if hasattr(n, 'lineno')]
                if body_lines:
                    ranges.append((min(body_lines), max(body_lines)))
                break
    return ranges


def scan(path):
    try:
        text = path.read_text(encoding='utf-8', errors='replace')
        if is_generated(text):
            return []
        tree = ast.parse(text)
    except (OSError, SyntaxError):
        return []

    skip = expected_failure_ranges(tree)
    hits = []
    for node in ast.walk(tree):
        # Only a discarded expression statement qualifies.
        if not isinstance(node, ast.Expr):
            continue
        if any(lo <= node.lineno <= hi for lo, hi in skip):
            continue
        # A mock assertion named without parentheses: an attribute access whose
        # value is thrown away, so the assertion never runs.
        if (isinstance(node.value, ast.Attribute)
                and node.value.attr in MOCK_ASSERTIONS):
            hits.append((node.lineno,
                         f'{node.value.attr} is named but never called'))
            continue
        if not isinstance(node.value, ast.Call):
            continue
        call = node.value
        name = call_name(call)
        if name is None:
            continue
        if any(lo <= node.lineno <= hi for lo, hi in skip):
            continue
        bare = name.rsplit('.', 1)[-1]

        if bare in UNITTEST:
            needed = UNITTEST[bare]
            # A keyword like msg= does not make it the callable form either,
            # but *args forwarding might, so leave Starred alone.
            if any(isinstance(a, ast.Starred) for a in call.args):
                continue
            if len(call.args) >= needed:
                continue
            if needed > 100:   # the no-callable-form sentinel
                hits.append((node.lineno, f'{name}(...) outside a with-block; '
                                          f'it has no callable form'))
            else:
                hits.append((node.lineno,
                             f'{name}(...) with {len(call.args)} arg(s), '
                             f'needs {needed} to run anything'))
        elif name in PYTEST:
            if any(isinstance(a, ast.Starred) for a in call.args):
                continue
            if len(call.args) >= PYTEST[name]:
                continue
            hits.append((node.lineno, f'{name}(...) with {len(call.args)} arg(s), '
                                      f'needs {PYTEST[name]} to run anything '
                                      f'or a with-block'))
    return hits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('roots', nargs='+')
    args = ap.parse_args()

    files = 0
    total = 0
    for root in args.roots:
        for path in pathlib.Path(root).rglob('*.py'):
            if SKIP_DIRS & set(path.parts):
                continue
            files += 1
            for line, why in scan(path):
                print(f'{path}:{line}  {why}')
                total += 1
    print(f'-- {total} discarded raises-assertion(s) in {files} python file(s) '
          f'across {len(args.roots)} root(s)', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())

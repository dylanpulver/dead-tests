#!/usr/bin/env python3
"""Find whole test FILES pytest never collects.

The sibling tools look for one uncollected function. This looks for the larger
version: a file full of tests whose NAME does not match the project's
`python_files` patterns, so pytest never imports it and every test inside is
dead at once. Nothing warns, because to pytest the file simply is not a test
file.

A file is reported only when all of these hold:

  * it lives under a test root (`testpaths`, or a dir named test/tests, or any
    directory holding a conftest.py)
  * it defines at least one `def test_*` or `class Test*` at top level
  * its name matches none of the project's own `python_files` patterns, read
    from the repo's config rather than assumed
  * no other file in the repo mentions its module name, so it is not a helper
    that some test imports
"""
import argparse
import configparser
import fnmatch
import pathlib
import re
import sys
import warnings

# Suppress the SCANNED repository's SyntaxWarnings. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is the subject's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path.
# changedetection.io alone emitted twelve lines of it, which buried this
# scanner's actual result. A scanner must not report its subject's warnings as
# if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)


# A generated file is not a place to find a bug: the defect, if any, is in the
# generator's input, and a PR against the output is rejected on sight. ccxt
# transpiles its Python test suite from TypeScript and every file says
# "PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN",
# which is how 18 candidates there turned out to be unfilable.
GENERATED_BANNER = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')


def is_generated(text):
    """True when the file announces itself as generated, judged on its head."""
    return bool(GENERATED_BANNER.search(text[:4000]))

DEFAULT_PATTERNS = ['test_*.py', '*_test.py']
TEST_DEF = re.compile(r'^(?:def\s+test_|class\s+Test)', re.M)
SKIP_NAMES = {'conftest.py', '__init__.py', 'setup.py'}
SKIP_DIRS = {'.git', '.tox', '.venv', 'venv', 'node_modules', 'build', 'dist',
             '.mypy_cache', '.pytest_cache', 'site-packages', '__pycache__',
             # .pixi and friends hold a whole vendored CPython, whose own
             # test/support/*_helper.py files are not this project's problem.
             '.pixi', '.conda', '.direnv', '.eggs', 'node_modules',
             # These hold files full of `def test_*` that a DIFFERENT tool runs,
             # so pytest not collecting them is the intent rather than a bug.
             # starlette's .github/workflows/benchmark.yml names
             # benchmarks/*_benchmark.py one by one, and click's pyproject points
             # both mypy (`files`) and pyright (`include`) at tests/typing.
             'benchmarks', 'benchmark', 'typing',
             # `examples/` ships runnable samples, and pyparsing's
             # examples/antlr_grammar_tests.py holds unittest methods that are
             # deliberately outside the suite.
             'examples', 'example',
             # Fixture material, not tests. langflow keeps
             # tests/data/component_with_templatefield.py as input to a test,
             # and django keeps tests/test_runner_apps/sample/pattern_tests.py
             # as a corpus for testing the runner's own pattern matching.
             'data', 'fixtures', 'fixture', 'sample', 'samples', 'testdata',
             # An ansible-style `plugins/test/` directory holds JINJA2 test
             # plugins, which are template filters named `test`, not pytest
             # tests. Five of ansible's candidates were this one class.
             'plugins'}


# Any dot-directory is tooling rather than the project's test suite. saleor
# keeps semgrep rules under .semgrep/, and a rule file carries `def test_...`
# cases for the rule itself, which semgrep reads and pytest should not.
def in_dot_dir(path) -> bool:
    return any(part.startswith('.') and part not in ('.', '..')
               for part in path.parts[:-1])


# A filename that announces itself as switched off is a decision, the same way a
# commented-out [Test] attribute is. msgpack carries
# test/uneeded_test_multithreading.py, spelling included.
DISABLED_NAME = re.compile(
    r'^(?:un+e+ded|unneeded|disabled|old|broken|skip|skipped|wip|dead)[_-]',
    re.I)

# A fuzz harness exports a `test_*` entry point for the fuzzer, not for pytest.
# lxml's src/lxml/tests/fuzz_xml_parse.py takes fuzzer-supplied bytes.
FUZZ_IMPORTS = ('import atheris', 'import afl', 'from hypothesis import')


def split_patterns(raw):
    """Split a `python_files` value and strip any quoting.

    pytest treats the value as whitespace-separated globs and does not strip
    quotes, but projects write them anyway: PyInstaller's pytest.ini has
    `python_files = "tests/functional/test_*.py" "tests/unit/test_*.py"`.
    Keeping the quotes makes every pattern match nothing, which reported all 100
    of its test files as uncollected while quoting the very pattern they match.
    """
    out = []
    for token in raw.split():
        out.append(token.strip('\'"'))
    return [t for t in out if t]


def read_patterns(root):
    """The project's own python_files, never a guess.

    A project that widens the patterns (`check_*.py`, `*_tests.py`) collects
    files this tool would otherwise report, so the config has to be read.
    """
    # pyproject.toml
    pp = root / 'pyproject.toml'
    if pp.is_file():
        try:
            import tomllib
            data = tomllib.loads(pp.read_text(encoding='utf-8'))
            opts = data.get('tool', {}).get('pytest', {}).get('ini_options', {})
            pats = opts.get('python_files')
            if pats:
                if isinstance(pats, str):
                    return split_patterns(pats)
                return [str(x).strip('\'"') for x in pats]
        except Exception:
            pass
    for name, section in (('pytest.ini', 'pytest'),
                          ('setup.cfg', 'tool:pytest'),
                          ('tox.ini', 'pytest')):
        path = root / name
        if not path.is_file():
            continue
        cp = configparser.ConfigParser()
        try:
            cp.read(path, encoding='utf-8')
        except Exception:
            continue
        if cp.has_option(section, 'python_files'):
            return split_patterns(cp.get(section, 'python_files'))
    return list(DEFAULT_PATTERNS)


# A file whose NAME says it is not a test is the author's own mechanism for
# keeping it out of the suite, exactly like the `check_*` methods in Pillow's
# Tests/test_uploader.py. Pillow keeps ten hand-run scripts under checks/ for
# segfault and large-memory reproductions, plus Tests/benchmarks.py, and all
# twelve were reported as uncollected test files.
HARNESS_NAME = re.compile(r'^(check_|benchmark|bench_|profile_|manual_|demo_)')
HARNESS_DIRS = {'checks', 'check', 'benchmarks', 'benchmark', 'profiling',
                'manual', 'demos',
                # FinancePy drives tests/regression/ from
                # scripts/run_all_regression_tests.py in its own CI workflow.
                'regression'}

# Many files in ONE directory sharing a non-matching name shape is a
# CONVENTION, not that many mistakes. FinancePy has 124 files named
# TestFinXxx.py under tests/regression/, run by their own script. A genuine
# forgotten file is one or two among properly named siblings. Same counting
# insight as the vacuous scanner's three-reflexive-comparisons rule.
HARNESS_DIR_THRESHOLD = 5


def is_manual_harness(path):
    if HARNESS_NAME.match(path.name):
        return True
    return bool(HARNESS_DIRS & set(path.parts))


def test_roots(root):
    roots = set()
    for path in root.rglob('conftest.py'):
        if SKIP_DIRS & set(path.parts):
            continue
        roots.add(path.parent)
    for path in root.rglob('*'):
        if path.is_dir() and path.name in ('test', 'tests') \
                and not SKIP_DIRS & set(path.parts):
            roots.add(path)
    return roots


def matches(path, root, patterns):
    """pytest's own matching rule.

    A pattern containing a slash is matched against the path, anything else
    against the basename. Matching only the basename made alembic's
    `tests/test_editor.py` look uncollected, because its project writes
    `python_files = tests/test_*.py`.
    """
    try:
        rel = path.relative_to(root).as_posix()
    except ValueError:
        rel = path.as_posix()
    for pattern in patterns:
        target = rel if '/' in pattern else path.name
        if fnmatch.fnmatch(target, pattern):
            return True
        # A slash-bearing pattern is anchored loosely by pytest, so also try
        # it against any trailing portion of the path.
        if '/' in pattern and fnmatch.fnmatch(rel, '*/' + pattern):
            return True
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('roots', nargs='+')
    args = ap.parse_args()

    total = 0
    scanned = 0
    for raw in args.roots:
        root = pathlib.Path(raw)
        patterns = read_patterns(root)
        roots = test_roots(root)
        if not roots:
            continue

        candidates = []
        for base in roots:
            for path in base.rglob('*.py'):
                if path.name.startswith('fuzz_') or path.name.endswith('_fuzz.py'):
                    continue
                if SKIP_DIRS & set(path.parts) or path.name in SKIP_NAMES:
                    continue
                if is_manual_harness(path):
                    continue
                if matches(path, root, patterns):
                    continue
                scanned += 1
                try:
                    text = path.read_text(encoding='utf-8', errors='replace')
                    if is_generated(text):
                        continue
                except OSError:
                    continue
                if not TEST_DEF.search(text):
                    continue
                candidates.append((path, len(TEST_DEF.findall(text))))

        # Nested test roots overlap, so one file can be found twice. Pillow's
        # Tests/benchmarks.py was reported twice because both Tests/ and an
        # ancestor qualified as roots and each rglob found it.
        seen = set()
        deduped = []
        for path, n in candidates:
            key = path.resolve()
            if key in seen:
                continue
            seen.add(key)
            deduped.append((path, n))
        candidates = deduped

        # Drop whole directories that look like a separate harness by weight.
        from collections import Counter
        per_dir = Counter(path.parent for path, _ in candidates)
        bulk = {d for d, n in per_dir.items() if n >= HARNESS_DIR_THRESHOLD}
        if bulk:
            candidates = [(p_, n) for p_, n in candidates if p_.parent not in bulk]

        if not candidates:
            continue

        # One pass over the repo to see which module names are referenced.
        corpus = []
        for path in root.rglob('*.py'):
            if SKIP_DIRS & set(path.parts):
                continue
            try:
                corpus.append((path, path.read_text(encoding='utf-8',
                                                   errors='replace')))
            except OSError:
                pass

        for path, n in candidates:
            if in_dot_dir(path) or DISABLED_NAME.match(path.name):
                continue
            stem = path.stem
            referenced = any(
                other != path and re.search(r'\b' + re.escape(stem) + r'\b', text)
                for other, text in corpus)
            if referenced:
                continue
            print(f'{path}  [{n} test def(s), name matches none of '
                  f'{" ".join(patterns)}]')
            total += 1

    print(f'-- {total} uncollected file(s) from {scanned} non-matching '
          f'file(s) in {len(args.roots)} root(s)', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())

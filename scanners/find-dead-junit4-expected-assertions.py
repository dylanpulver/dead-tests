#!/usr/bin/env python3
"""Find assertions made unreachable by JUnit 4's `@Test(expected = X.class)`.

THE PROOF, the same one behind find-dead-pytest-raises-assertions.py. The
annotation makes the WHOLE method body expected-to-throw, so for the test to
pass something in it must throw `X`. An `assert*` call can only throw
`AssertionError`. So when `X` cannot be an AssertionError and the assertion is
the LAST top-level statement of the body, it is provably unreachable.

A JAVA DETAIL THAT DIFFERS FROM PYTHON. `AssertionError extends Error extends
Throwable`, and `Error` is NOT an `Exception`. So `expected = Exception.class`
still leaves the assertion provably dead, where Python's `except Exception`
would catch its AssertionError and spare it. Only `Throwable`, `Error` and
`AssertionError` admit the assertion as the raiser.

This is the shape that produced cakephp#19760, cakephp#19761 and
api-platform#8772 in PHP (`expectException` declared first) and sktime#11673 in
Python. JUnit 4's `expected` attribute is its closest analogue, because the
annotation sits above the method exactly as `expectException` sits above the
body. JUnit 5 dropped the attribute for `assertThrows`, so this applies to
JUnit 4 style only.

BRACE COUNTING IS DONE ON A STRIPPED COPY. String literals, char literals and
comments are blanked first, preserving offsets, because an earlier Java scanner
in this toolkit cost four separate bugs to brace and annotation handling, three
of them from counting braces that were inside something else.

Reported only when all of these hold:
  * the method carries `@Test(expected = X.class)` with X outside the admitting set
  * the body has two or more top-level statements
  * the last top-level statement is an `assert*` / `fail` call

Fixture: cases/javaexpected, 11 cases, 3 expected hits, with
the expected answer written down before the first run.

Usage: find-dead-junit4-expected-assertions.py <path>...
"""
import re
import sys
from pathlib import Path

SKIP_DIRS = {'.git', 'target', 'build', 'out', 'node_modules', '.gradle',
             '.idea', 'generated', 'generated-sources'}

GENERATED = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')

# Only these can BE an AssertionError, so only these spare the assertion.
ADMITS_ASSERTION_ERROR = {'Throwable', 'Error', 'AssertionError',
                          'java.lang.Throwable', 'java.lang.Error',
                          'java.lang.AssertionError'}

TEST_EXPECTED = re.compile(
    r'@Test\s*\(\s*expected\s*=\s*([\w.]+)\s*\.\s*class\s*\)')

ASSERTION_START = re.compile(r'^assert\w*\s*\(')

# A trailing bare `fail("... did not throw ...")` is the OPPOSITE of a dead
# assertion: it is the guard that fires when the call under test returns
# normally. Under `@Test(expected = X)` that `fail` throws AssertionError, which
# is not X, so the test fails with the author's own message. It is unreachable
# only on the passing path, which is the entire point.
#
# Keeping `fail` in ASSERTION_START made this seam 69% noise: conductor reported
# 29 hits and 20 were this idiom, every one of them correct code.
FAIL_GUARD = re.compile(r'^(?:\w+\.)?fail\s*\(')

# Counted so a suppression is visible rather than silent.
GUARDS = [0]


def blank_literals_and_comments(src):
    """Replace strings, chars and comments with spaces, preserving offsets."""
    out = list(src)
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                if src[j] == '\\':
                    j += 1
                j += 1
            for k in range(i, min(j + 1, n)):
                if src[k] != '\n':
                    out[k] = ' '
            i = j + 1
        elif c == "'":
            j = i + 1
            while j < n and src[j] != "'":
                if src[j] == '\\':
                    j += 1
                j += 1
            for k in range(i, min(j + 1, n)):
                if src[k] != '\n':
                    out[k] = ' '
            i = j + 1
        elif c == '/' and i + 1 < n and src[i + 1] == '/':
            j = src.find('\n', i)
            j = n if j == -1 else j
            for k in range(i, j):
                out[k] = ' '
            i = j
        elif c == '/' and i + 1 < n and src[i + 1] == '*':
            j = src.find('*/', i + 2)
            j = n if j == -1 else j + 2
            for k in range(i, j):
                if src[k] != '\n':
                    out[k] = ' '
            i = j
        else:
            i += 1
    return ''.join(out)


def method_body_span(stripped, from_pos):
    """(start, end) just inside the method's braces, or None."""
    open_at = stripped.find('{', from_pos)
    if open_at == -1:
        return None
    depth = 0
    for i in range(open_at, len(stripped)):
        if stripped[i] == '{':
            depth += 1
        elif stripped[i] == '}':
            depth -= 1
            if depth == 0:
                return open_at + 1, i
    return None


def top_level_statements(stripped, start, end):
    """Text spans of statements at depth 0 within the body."""
    stmts = []
    depth = 0
    cur = start
    for i in range(start, end):
        c = stripped[i]
        if c in '{([':
            depth += 1
        elif c in '})]':
            depth -= 1
            if depth == 0 and c == '}':
                stmts.append((cur, i + 1))   # a nested block ends a statement
                cur = i + 1
        elif c == ';' and depth == 0:
            stmts.append((cur, i + 1))
            cur = i + 1
    return [(a, b) for a, b in stmts if stripped[a:b].strip()]


def scan_file(path):
    try:
        src = path.read_text(errors='replace')
    except OSError:
        return []
    if GENERATED.search(src[:4000]) or '@Test' not in src:
        return []
    stripped = blank_literals_and_comments(src)
    hits = []
    for m in TEST_EXPECTED.finditer(stripped):
        exc = m.group(1)
        if exc.split('.')[-1] in ADMITS_ASSERTION_ERROR or exc in ADMITS_ASSERTION_ERROR:
            continue
        span = method_body_span(stripped, m.end())
        if not span:
            continue
        stmts = top_level_statements(stripped, *span)
        if len(stmts) < 2:
            continue
        a, b = stmts[-1]
        last = stripped[a:b].strip()
        if FAIL_GUARD.match(last):
            GUARDS[0] += 1
            continue
        if not ASSERTION_START.match(last):
            continue
        line = src[:a].count('\n') + 1
        real = ' '.join(src[a:b].split())[:110]
        hits.append(f'{path}:{line}: @Test(expected = {exc}.class): {real}')
    return hits


def main():
    roots = [x for x in sys.argv[1:] if not x.startswith('--')] or ['.']
    hits, nfiles = [], 0
    for root in roots:
        for f in Path(root).rglob('*.java'):
            if SKIP_DIRS & set(f.parts):
                continue
            nfiles += 1
            hits += scan_file(f)
    print('\n'.join(hits))
    note = f'; {GUARDS[0]} trailing fail() guard(s) suppressed' if GUARDS[0] else ''
    print(f'-- {len(hits)} provable hit(s) from {nfiles} java file(s){note}',
          file=sys.stderr)


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Find test functions that swallow an exception and assert nothing, so they cannot fail.

THE SHAPE:

    def test_insert_rejects_bad_row():
        try:
            db.insert(bad_row)
        except KeyError:
            pass

The test is named for a rejection it never verifies. If `insert` stops raising,
the body runs to the end and the test still passes. Nothing distinguishes
"raised" from "did not raise". The correct forms are `pytest.raises`, or a
`fail()` as the last statement inside the `try`.

This is the inverse of find-dead-pytest-raises-assertions.py: there the
assertion exists and cannot run, here the assertion does not exist at all.

REPORTED only when ALL of these hold, which is what keeps precision usable:

  * the function is a test (`test_` prefix, or `@pytest.mark` / unittest method)
  * it contains a `try` whose EVERY handler body is only `pass`, `...`, or a
    docstring, so no handler inspects what it caught
  * the function contains NO assertion anywhere: no `assert`, no `assert*()`
    call, no `fail()` / `pytest.fail()`. One assertion anywhere is enough to
    make the test able to fail, which is why the fixture's cleanup case and
    optional-import case are both excluded by this single rule rather than by
    special-casing them.
  * no `@pytest.mark.skip` / `xfail` on the function

DELIBERATELY EXCLUDED, because each is a convention rather than a defect:

  * handlers catching only `ImportError` / `ModuleNotFoundError`, which guard an
    optional dependency. A test that does nothing but try an import is a smoke
    test, not a broken assertion.
  * handlers that bind the exception and use it (`except E as e: assert ...`),
    caught by the no-assertion rule anyway.

The caught exception types are printed so the triage can tell a narrow
expected-to-raise case from a broad `except Exception` that also hides crashes.

Fixture: cases/pyswallow, 9 cases, exactly 3 expected hits,
expectations written down before the first run.

Usage: find-swallowed-test-exceptions.py <path>...
"""
import ast
import re
import sys
import warnings

# Suppress the SCANNED repository's SyntaxWarnings. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is the subject's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path.
# changedetection.io alone emitted twelve lines of it, which buried this
# scanner's actual result. A scanner must not report its subject's warnings as
# if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)

import warnings
from pathlib import Path

# Parsing other projects' sources emits their SyntaxWarnings on OUR stderr, which
# buried this tool's own `-- N hit(s) from M files` line in a 401-repo run. The
# denominator is the part that proves the walk was not short, so keep it readable.
warnings.simplefilter('ignore', SyntaxWarning)

SKIP_DIRS = {'.git', 'node_modules', '.tox', '.venv', 'venv', 'build', 'dist',
             '.mypy_cache', '.pytest_cache', 'site-packages', '.eggs',
             '.pixi', '.conda', 'conda-meta', 'test-files', '.hatch', '.nox'}

GENERATED = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')

# Guarding an optional dependency is a convention, not a broken assertion.
DEPENDENCY_GUARDS = {'ImportError', 'ModuleNotFoundError'}

# `try/except: pass` expresses TOLERANCE, not a requirement, so a missing
# assertion is often exactly what the author meant (celery's test_lt says
# "order doesn't matter" in a comment). The one case where tolerance contradicts
# the author is when the test's NAME claims a rejection it never verifies.
# --name-claims reports only those, trading recall for precision.
NAME_CLAIMS_REJECTION = re.compile(
    r'(?i)(invalid|reject|refus|error|raise|fail|bad_|_bad|malformed|'
    r'illegal|forbidden|denied|unsupported|duplicate|conflict|'
    r'too_(long|short|large|small|many)|out_of_range)')

# A NEGATED name claims the opposite and tolerating is then correct.
# `test_no_error`, `test_does_not_raise` and `test_without_failure` are common,
# and the fixture's own `test_swallow_no_fail` matched on the `fail` inside
# `no_fail`, which is how this class surfaced before it reached a real repo.
# Lookbehinds matter: `valid_` matches inside `invalid_azure...` and `accept`
# inside `unacceptable`, which would negate the very names we want.
NAME_NEGATES = re.compile(
    r'(?i)(no_|not_|non_|never_|without_|succe|(?<!in)valid_|allowed'
    r'|(?<!un)accept)')


def dotted(node):
    if isinstance(node, ast.Attribute):
        return node.attr
    return getattr(node, 'id', '')


def is_assertion(node):
    """True for anything that can make a test fail on purpose."""
    if isinstance(node, ast.Assert):
        return True
    if isinstance(node, ast.Call):
        n = dotted(node.func)
        if n.startswith(('assert', 'failUnless', 'failIf')) or n == 'fail':
            return True
        # `with pytest.raises(...)` IS an assertion and can fail the test. Missing
        # this read every raises-only test as asserting nothing, which is how an
        # nltk test whose try/except pass was mere cleanup in a `finally` got
        # reported. `self.assertRaises` was already covered by the assert prefix.
        if n in ('raises', 'warns', 'deprecated_call'):
            return True
    # `raise AssertionError(...)` is a hand-rolled fail.
    if isinstance(node, ast.Raise) and node.exc is not None:
        exc = node.exc.func if isinstance(node.exc, ast.Call) else node.exc
        if dotted(exc) in ('AssertionError', 'Failed'):
            return True
    return False


def has_assertion(fn):
    return any(is_assertion(n) for n in ast.walk(fn))


def body_is_only_pass(body):
    """True when a handler body does nothing: pass, ..., or a bare docstring."""
    for stmt in body:
        if isinstance(stmt, ast.Pass):
            continue
        if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Constant):
            continue  # docstring or `...`
        return False
    return bool(body)


def caught_names(handler):
    t = handler.type
    if t is None:
        return ['<bare except>']
    if isinstance(t, (ast.Tuple, ast.List)):
        return [dotted(e) or '?' for e in t.elts]
    return [dotted(t) or '?']


def is_skipped(fn):
    for d in fn.decorator_list:
        src = d.func if isinstance(d, ast.Call) else d
        name = ''
        while isinstance(src, ast.Attribute):
            name = src.attr + '.' + name
            src = src.value
        name = (getattr(src, 'id', '') + '.' + name).strip('.')
        if 'skip' in name or 'xfail' in name:
            return True
    return False


def is_test_file(path):
    """A `test` prefix on a FUNCTION name does not make it a test.

    bokeh ships `def test_condition(s, y, H) -> bool` as a nested predicate
    inside `src/bokeh/models/util/structure.py`, production code, and it
    matched on the prefix alone. Require the FILE to be a test file too.
    """
    n = path.name
    if n.startswith('fuzz') or n.endswith('_fuzz.py'):
        return False   # a fuzz target swallows by design, crashes are the signal
    # A benchmark measures the cost of an error path; swallowing is the point.
    # All four pydantic hits were under pydantic-core/tests/benchmarks/.
    if any(part in ('benchmarks', 'benchmark', 'perf') for part in path.parts):
        return False
    if n == 'conftest.py' or n.startswith('test_') or n.endswith('_test.py'):
        return True
    return any(part in ('test', 'tests') for part in path.parts)


# A method named `test` can be a helper rather than a test. pyca/cryptography's
# conftest has `SubTests.test`, a @contextlib.contextmanager implementing a
# miniature pytest-subtests that swallows pytest.skip.Exception on purpose.
NOT_A_TEST_DECORATORS = ('contextmanager', 'asynccontextmanager', 'fixture',
                         'property', 'cached_property', 'staticmethod',
                         'classmethod', 'setter')


def looks_like_test(fn):
    for d in fn.decorator_list:
        if any(w in ast.dump(d) for w in NOT_A_TEST_DECORATORS):
            return False
    return fn.name.startswith('test') or any(
        'pytest.mark' in ast.dump(d) for d in fn.decorator_list)


def is_setup_swallow(fn, node):
    """True when the swallow precedes the test's actual work, so it is cleanup.

    `try: close_it() except NotFound: pass` as a test's FIRST step means "close
    it if it happens to be open", and the exception is the expected case.
    EFForg/privacybadger does this in two popup tests, then does the real work
    and asserts through a helper that raises. A swallow is only the test's
    conclusion when nothing follows it.
    """
    for i, stmt in enumerate(fn.body):
        if stmt is node:
            return any(not isinstance(rest, ast.Pass) for rest in fn.body[i + 1:])
    return False


def scan_file(path):
    try:
        src = path.read_text(errors='replace')
    except OSError:
        return []
    if GENERATED.search(src[:4000]):
        return []
    if 'atheris' in src[:4000]:
        return []   # fuzz harness
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return []
    hits = []
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if not looks_like_test(fn) or is_skipped(fn):
            continue
        if has_assertion(fn):
            continue
        for node in ast.walk(fn):
            if not isinstance(node, ast.Try):
                continue
            if not node.handlers:
                continue
            if not all(body_is_only_pass(h.body) for h in node.handlers):
                continue
            # `try/except/else: raise` is the canonical pre-pytest form of "this
            # must raise": the else branch runs only when nothing was raised, so
            # it DOES detect non-raising. petl's test_records_errors and
            # tenacity's test_reraise both use it with a bare
            # `raise Exception('expected exception not raised')`, which
            # is_assertion does not count because a bare raise elsewhere in a
            # test is not an assertion. Judge it here, at the construct.
            if any(isinstance(n, ast.Raise) or is_assertion(n)
                   for stmt in node.orelse for n in ast.walk(stmt)):
                continue
            if is_setup_swallow(fn, node):
                continue
            names = [n for h in node.handlers for n in caught_names(h)]
            if names and all(n in DEPENDENCY_GUARDS for n in names):
                continue
            claims = bool(NAME_CLAIMS_REJECTION.search(fn.name)) and \
                not NAME_NEGATES.search(fn.name)
            if NAME_CLAIMS_ONLY and not claims:
                break
            mark = ' NAME-CLAIMS-REJECTION' if claims else ''
            hits.append(f'{path}:{node.lineno}: {fn.name}: '
                        f'swallows {"/".join(names)}, function asserts nothing{mark}')
            break
    return hits


NAME_CLAIMS_ONLY = False


def main():
    global NAME_CLAIMS_ONLY
    NAME_CLAIMS_ONLY = '--name-claims' in sys.argv
    roots = [a for a in sys.argv[1:] if not a.startswith('--')] or ['.']
    hits, nfiles = [], 0
    for root in roots:
        for f in Path(root).rglob('*.py'):
            if SKIP_DIRS & set(f.parts):
                continue
            if not is_test_file(f):
                continue
            nfiles += 1
            hits += scan_file(f)
    print('\n'.join(hits))
    print(f'-- {len(hits)} hit(s) from {nfiles} python file(s)', file=sys.stderr)


if __name__ == '__main__':
    main()

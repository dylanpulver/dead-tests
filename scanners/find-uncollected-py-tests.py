#!/usr/bin/env python3
"""Find pytest tests that are never collected, so never run.

Two shapes, both silent: no error, no skip, no mention in the output.

  1. A module-level function in a test file that asserts things but is not named
     `test_*`, and nothing calls it. pytest collects by name, so it never runs.
  2. A CLASS holding `test_*` methods whose own name does not start with
     `Test`. In theory pytest skips the whole class. In practice this is
     **idiomatic Python** and almost always a shared abstract base that `Test*`
     subclasses inherit, so the tests do run: measured across 59,510 test files
     it produced 5,239 hits and essentially all were bases or mixins
     (`DatasetIOBase`, `CommonTests`, `EventLoopTestMixin`). It is therefore
     OFF unless `--classes` is passed, and even then every hit needs reading.

The PHP counterpart is `find-uncollected-php-tests.py`; the equivalent Sylius
find was a single method left with a PhpSpec name after a migration, and it had
accumulated two faults inside it by the time anyone ran it.

Honest shapes that are filtered out:

  1. Fixtures and hooks: anything decorated (`@pytest.fixture`, `@hypothesis
     .given`, `@contextmanager`), plus `setup_*` / `teardown_*` / conftest
     helpers, which pytest or the author calls by other means.
  2. Helpers called from elsewhere in the same module, including indirectly as
     a bare name passed to `parametrize` or `mark.usefixtures`.
  3. Names starting with `_`, which read as deliberately private helpers.
  4. Functions with no assert and no `pytest.raises`, which are plain helpers.

A name referenced anywhere else in the tree is never reported, because a
module of shared `assert_*` helpers looks exactly like a module of uncollected
tests from inside one file. ccxt's `test_shared_methods.py` produced 18 hits
that way, every one a helper called from 4 to 18 other files. Pass
`--no-cross-file` to see them anyway; the suppressed count is always printed.
"""
import ast
import re
import sys
import warnings

# The SyntaxWarnings that used to appear in this tool's output came from the
# SCANNED repository's source, not from here. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is unsloth's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path. unsloth alone
# printed eight lines of it. A scanner must not report its subject's warnings
# as if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)
from pathlib import Path

# A generated file is not a place to find a bug: the defect, if any, is in the
# generator's input, and a PR against the output is rejected on sight. ccxt
# transpiles its Python test suite from TypeScript and every file says
# "PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN",
# which is how 18 candidates there turned out to be unfilable.
GENERATED_BANNER = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')


# Prefixes that deliberately keep a function OUT of collection. bokeh's
# tests/unit/bokeh/test_typing.py says so in its own header: the file is for mypy
# only, and "attempting to run this test file with pytest with `mypy_` removed
# will result in inevitable errors".
# `t_est_` is statsmodels' idiom for switching a test off, not a typo: commit
# f042e5e4e, "TST: disable failing random test, imputation, mediation", renamed
# them that way on purpose. Check `git log -S` before overriding any of these.
# `x_test_` is the same idiom with a separator: django-cms carries exactly one,
# `TestLanguagesNoDefault.x_test_get_languages_default_site`, and it is the only
# `x_test_` in that repo, so it is a one-off switch-off rather than a convention
# the file follows. A recognisable disable marker is a decision, the same way a
# commented-out `[Test]` attribute is in the .NET scanner.
PARK_PREFIXES = ('mypy_test', 'notest', 'nottest', 'xtest', 'x_test',
                 'disabled_test', 'skip_test', 'broken_test', 't_est')


def is_generated(text):
    """True when the file announces itself as generated, judged on its head."""
    return bool(GENERATED_BANNER.search(text[:4000]))

REPORT_CLASSES = '--classes' in sys.argv

DECORATOR_EXEMPT = ('fixture', 'given', 'contextmanager', 'setup', 'teardown',
                    'hookimpl', 'hookspec', 'composite', 'register')


def decorator_names(node):
    out = []
    for d in node.decorator_list:
        cur = d.func if isinstance(d, ast.Call) else d
        while isinstance(cur, ast.Attribute):
            out.append(cur.attr)
            cur = cur.value
        if isinstance(cur, ast.Name):
            out.append(cur.id)
    return out


def asserts(node):
    for sub in ast.walk(node):
        if isinstance(sub, ast.Assert):
            return True
        # unittest asserts by METHOD CALL, not by the `assert` statement, so a
        # TestCase method full of `self.assertEqual(...)` has no ast.Assert in
        # it at all. Missing this made the method-level pass blind to exactly
        # the framework it was added for.
        if isinstance(sub, ast.Call):
            f = sub.func
            nm = f.attr if isinstance(f, ast.Attribute) else getattr(f, 'id', '')
            if nm.startswith(('assert', 'failUnless', 'failIf')) or nm == 'fail':
                return True
        if isinstance(sub, ast.With):
            for item in sub.items:
                call = item.context_expr
                if isinstance(call, ast.Call):
                    f = call.func
                    name = f.attr if isinstance(f, ast.Attribute) else getattr(f, 'id', '')
                    if name in ('raises', 'warns', 'deprecated_call'):
                        return True
    return False


def is_testcase_subclass(cls):
    for base in cls.bases:
        name = base.attr if isinstance(base, ast.Attribute) else getattr(base, 'id', '')
        if 'TestCase' in name or 'TestCase' in ast.dump(base):
            return True
    return False


# unittest, pytest and TestCase itself call these; a custom `assert*` helper is
# exempt by convention, the same way a leading underscore is.
METHOD_HOOKS = re.compile(
    r'^(setUp|tearDown|setUpClass|tearDownClass|setUpTestData|asyncSetUp|'
    r'asyncTearDown|setup_method|teardown_method|setup_class|teardown_class|'
    r'run|runTest|shortDescription|id|subTest|addCleanup|doCleanups|'
    r'skipTest|fail|countTestCases|defaultTestResult|debug|assert\w*|'
    # django_test_migrations calls prepare() on every MigratorTestCase subclass
    # before running the migration, and test_after_migration() after it. Six of
    # InvenTree's seven candidates were `prepare`, one per migration test class.
    r'prepare|test_after_migration|'
    r'maxDiff|__\w+__)$')


def collected_class(cls):
    """True when pytest or unittest collects test methods from this class.

    pytest collects `Test*` classes; unittest collects any TestCase subclass.
    A class that is neither is reported by the separate class-level check.
    """
    return cls.name.startswith('Test') or is_testcase_subclass(cls)



# A function that takes ARGUMENTS is a helper, not a forgotten test. pytest
# never collected it, so those parameters were never resolved as fixtures, and
# in practice they are helper arguments. Measured 2026-10-31 on five hits:
# prefect's `assert_flow_run_is_deleted(prefect_client, flow_run_id)`,
# `assert_task_run_is_deleted(...)`, `pausing_long_exposure(...)` and pymc's
# `assert_equal_hash(classA, classB)` all take 2 or 3, while the one genuine
# find, prefect's `ensure_valid_bitbucket_username_passes()`, takes none.
# Renaming a parameterised helper to `test_*` would be WRONG, not a fix.
#
# Parameters that are all standard pytest fixtures are kept, since such a
# function really is a test someone forgot to prefix. A project fixture from
# conftest is not recognisable here, so this trades a little recall for
# precision, which is the right way round for a 135-hit corpus.
PYTEST_BUILTIN_FIXTURES = {
    'tmp_path', 'tmp_path_factory', 'tmpdir', 'tmpdir_factory', 'monkeypatch',
    'capsys', 'capfd', 'caplog', 'recwarn', 'request', 'pytestconfig',
    'cache', 'doctest_namespace', 'record_property', 'subtests',
}


def takes_non_fixture_args(node, skip_self=False):
    a = node.args
    names = [x.arg for x in (a.posonlyargs + a.args + a.kwonlyargs)]
    if skip_self and names and names[0] in ('self', 'cls'):
        names = names[1:]
    if a.vararg:
        names.append(a.vararg.arg)
    if a.kwarg:
        names.append(a.kwarg.arg)
    names = [x for x in names if x not in ('self', 'cls')]
    if not names:
        return False
    return not all(x in PYTEST_BUILTIN_FIXTURES for x in names)


def has_any_collected_test(tree):
    """Does pytest collect ANYTHING from this module?

    A forgotten test is recognised by its SIBLINGS running while it does not.
    A module with no collected test at all is not a test module that lost one,
    it is a manual harness. Pillow's Tests/test_uploader.py holds only
    `check_upload_equal` and `check_upload_similar`, which exist to FAIL on
    purpose so a developer can verify the error-image uploader: helper.py's
    `assert_image_equal` calls `upload(a, b)` before `pytest.fail`. They are
    named `check_*` precisely so pytest never collects them, and reporting
    them as forgotten tests inverts the author's intent.
    """
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name.startswith('test'):
                return True
        elif isinstance(node, ast.ClassDef) and collected_class(node):
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    if sub.name.startswith('test'):
                        return True
    return False


def scan_file(path, text, tree, external=frozenset()):
    hits = []
    suppressed = []
    if not has_any_collected_test(tree):
        return hits, suppressed
    # Every bare name used anywhere, so a called helper is not reported.
    used = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
    used |= {n.attr for n in ast.walk(tree) if isinstance(n, ast.Attribute)}
    used |= {c.value for c in ast.walk(tree)
             if isinstance(c, ast.Constant) and isinstance(c.value, str)}

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            n = node.name
            if n.startswith('test') or n.startswith('_'):
                continue
            # Case-insensitive, because unittest's MODULE-level hooks are
            # camelCase: `setUpModule` and `tearDownModule` are called by the
            # runner, not by name, and frappe's test_test_utils.py defines
            # `tearDownModule()`, which the lowercase-only check reported.
            if n.lower().startswith(('setup', 'teardown', 'pytest_')) \
                    or n == 'load_tests':
                continue
            if n.startswith(PARK_PREFIXES):
                continue
            if any(d.startswith(DECORATOR_EXEMPT) or d in DECORATOR_EXEMPT
                   for d in decorator_names(node)):
                continue
            if not asserts(node):
                continue
            if takes_non_fixture_args(node):
                continue
            if n in used:
                continue
            if n in external:
                # Called or imported from another module, so it is a helper.
                suppressed.append(n)
                continue
            hits.append(f'{path}:{node.lineno}: function {n}() is never collected')

        elif isinstance(node, ast.ClassDef) and collected_class(node):
            # A method here is collected only when named test*, so an asserting
            # method without the prefix is dead. The PHP and Java twin of this
            # seam converted; unittest is the biggest population it has.
            for m in node.body:
                if not isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                mn = m.name
                if mn.startswith(PARK_PREFIXES):
                    continue
                if mn.startswith('test') or mn.startswith('_'):
                    continue
                if METHOD_HOOKS.match(mn):
                    continue
                if any(d.startswith(DECORATOR_EXEMPT) or d in DECORATOR_EXEMPT
                       for d in decorator_names(m)):
                    continue
                if not asserts(m):
                    continue
                # A method taking anything beyond self and pytest's builtin
                # fixtures cannot be collected as a test at all, so it is a
                # helper by construction. readthedocs' add_project_to_team
                # takes (self, team="foobar", projects=None, test=True) and
                # returns the response, which is a helper however it is named.
                # The module-level branch already applied this check; the
                # method branch did not.
                if takes_non_fixture_args(m, skip_self=True):
                    continue
                if mn in used:
                    continue
                if mn in external:
                    suppressed.append(mn)
                    continue
                # Two different findings wear the same shape, and conflating
                # them wastes triage. A method whose name starts with `test`
                # was MEANT to be collected and is not: that is the seam. One
                # whose name does not was meant to be CALLED, so an uncalled
                # one is dead helper code, a weaker and differently-fixed
                # thing. InvenTree's ViewTests.get_index_page asserts a 200 and
                # its docstring says "used for subsequent unit tests", yet
                # nothing calls it; reporting that as "never collected" reads
                # as a dead test and it is not.
                # Case-INSENSITIVE: a method named `TestDoH3PostRequest` in a
                # test class was plainly meant to be a test, and the capital T
                # IS the bug, since pytest only collects a lowercase `test`
                # prefix. Matching case-sensitively labelled dnspython's two
                # DoH3 methods as dead helpers, which is the opposite of what
                # our own open PR #1400 there says about them.
                if mn.lower().startswith('test'):
                    hits.append(
                        f'{path}:{m.lineno}: method {node.name}.{mn}() '
                        f'is never collected')
                else:
                    # NEUTRAL on purpose. Which of the two it is cannot be
                    # decided from the name, and claiming either way misleads.
                    # `list_of_colors_in_cmap_raises_error` and
                    # `output_grid_deprecation_warning_dap2dataset` in xarray
                    # read as test descriptions; `add_project_to_team` in
                    # readthedocs and `sample_volume_rectangular` in trimesh
                    # read as actions a helper performs. The earlier wording
                    # asserted "dead helper" for all of them, and xarray's is
                    # already queued as an uncollected TEST, the opposite claim.
                    hits.append(
                        f'{path}:{m.lineno}: {node.name}.{mn}() asserts, is '
                        f'not collected, and nothing calls it (read it: a '
                        f'forgotten test, or dead helper code)')

        elif isinstance(node, ast.ClassDef) and REPORT_CLASSES:
            if node.name.startswith('Test') or is_testcase_subclass(node):
                continue
            inner = [m.name for m in node.body
                     if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))
                     and m.name.startswith('test')]
            if not inner:
                continue
            hits.append(
                f'{path}:{node.lineno}: class {node.name} holds '
                f'{len(inner)} test_* method(s) but lacks the Test prefix')
    return hits, suppressed


def interesting_files(roots):
    """Every .py file under the roots that is not vendored or a virtualenv."""
    for root in roots:
        for f in sorted(Path(root).rglob('*.py')):
            parts = set(f.parts)
            if parts & {'.git', 'build', 'dist', 'node_modules', '.tox', 'venv',
                        'site-packages', 'vendor', '.eggs', '__pypackages__',
                        'mutants'}:
                continue
            if any(d.startswith(('.venv', 'venv', '.env', '.pixi', '.conda'))
                   for d in f.parts):
                continue
            yield f


def reference_map(roots):
    """name -> set of files that reference it.

    The callers of a shared test helper live in OTHER modules, and those modules
    are usually themselves test files, so neither a per-file `used` set nor a
    global one computed with test files excluded can tell a helper from an
    uncollected test. What distinguishes them is being referenced from a file
    OTHER than the one defining it, which needs the per-file breakdown.
    """
    refs = {}
    for f in interesting_files(roots):
        try:
            tree = ast.parse(f.read_text(errors='replace'))
        except (OSError, SyntaxError):
            continue
        for n in ast.walk(tree):
            name = None
            if isinstance(n, ast.Name):
                name = n.id
            elif isinstance(n, ast.Attribute):
                name = n.attr
            elif isinstance(n, ast.alias):
                name = (n.asname or n.name).split('.')[-1]
            elif isinstance(n, ast.Constant) and isinstance(n.value, str):
                name = n.value
            if name:
                refs.setdefault(name, set()).add(f)
    return refs


def main():
    roots = [a for a in sys.argv[1:] if not a.startswith('--')] or ['.']
    cross_file = '--no-cross-file' not in sys.argv
    hits = []
    suppressed_total = 0
    examined = 0
    test_files = []
    for root in roots:
        for f in sorted(Path(root).rglob('*.py')):
            parts = set(f.parts)
            if parts & {'.git', 'build', 'dist', 'node_modules', '.tox', 'venv',
                        'site-packages', 'vendor', '.eggs', '__pypackages__',
                        'mutants'}:
                continue
            # Any venv flavour: .venv, .venv-dev, venv311, env.
            if any(d.startswith(('.venv', 'venv', '.env', '.pixi', '.conda')) for d in f.parts):
                continue
            if not (f.name.startswith('test_') or f.name.endswith('_test.py')):
                continue
            try:
                text = f.read_text(errors='replace')
                tree = ast.parse(text)
            except (OSError, SyntaxError):
                continue
            if is_generated(text):
                continue
            examined += 1
            test_files.append((f, text, tree))

    refs = reference_map(roots) if (cross_file and test_files) else {}
    for f, text, tree in test_files:
        # A name referenced from any file but this one is a helper, not a test.
        external = {n for n, files in refs.items() if files - {f}}
        h, sup = scan_file(f, text, tree, external)
        hits.extend(h)
        suppressed_total += len(sup)
    print('\n'.join(h for h in hits if h))
    msg = (f'-- {len(hits)} candidate(s) from {examined} test file(s) in '
           f'{len(roots)} root(s)')
    if suppressed_total:
        msg += f', {suppressed_total} suppressed as helpers referenced elsewhere'
    print(msg, file=sys.stderr)


if __name__ == '__main__':
    main()

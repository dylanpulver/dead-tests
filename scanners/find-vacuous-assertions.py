#!/usr/bin/env python3
"""Find test assertions that compare a value to itself, so they cannot fail.

`assertEqual(foo, foo)`, `assert a.b == a.b`, `assertIs(x, x)`: the two sides are
the same expression, so the assertion holds whatever the code does. Third member
of the same family as the dead assertion and the shadowed test: an assertion that
is present, collected, and worthless.

Comparison is structural, over the AST with line numbers stripped, so
`assertEqual(r["a"], r["a"])` is caught while `assertEqual(a, b)` is not.

False positives to read for, all real:
  1. A deliberate NaN check is `x != x`, never `x == x`; `!=` and assertNotEqual
     are therefore excluded here.
  2. Idempotence or caching checks, where calling the same expression twice is
     the point (`assertIs(obj.cached, obj.cached)`). Rare, and reads as such.
  3. An expression whose two evaluations genuinely differ, e.g. `next(it) == next(it)`
     or anything calling a random/clock function. Flagged with a SIDE-EFFECT note
     when either side contains a call.

Usage: find-vacuous-assertions.py [path ...]
"""
import ast
import re
import sys
import warnings

# Suppress the SCANNED repository's SyntaxWarnings. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is the subject's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path.
# changedetection.io alone emitted twelve lines of it, which buried this
# scanner's actual result. A scanner must not report its subject's warnings as
# if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)

# No summary line meant a clean run printed nothing, and a run whose output I
# piped wrongly also printed nothing. I counted a 34-repo corpus twice off this
# tool and got two different wrong answers before noticing it reports no
# denominator at all. Report the denominator, always.
STATS = {"files": 0, "hits": 0}

from pathlib import Path

# A generated file is not a place to find a bug: the defect, if any, is in the
# generator's input, and a PR against the output is rejected on sight. ccxt
# transpiles its Python test suite from TypeScript and every file says
# "PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN",
# which is how 18 candidates there turned out to be unfilable.
GENERATED_BANNER = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')


def is_generated(text):
    """True when the file announces itself as generated, judged on its head."""
    return bool(GENERATED_BANNER.search(text[:4000]))

SELF_EQUAL_METHODS = {
    "assertEqual", "assertEquals", "assertIs", "assertAlmostEqual",
    "assertListEqual", "assertDictEqual", "assertSetEqual", "assertTupleEqual",
    "assertSequenceEqual", "assertMultiLineEqual", "assertCountEqual",
}


def norm(node):
    """Structural dump with positions removed, so two spellings compare equal."""
    return ast.dump(node, annotate_fields=True, include_attributes=False)


def has_call(node):
    return any(isinstance(n, ast.Call) for n in ast.walk(node))


def enclosing_function(tree, target):
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for sub in ast.walk(fn):
            if sub is target:
                return fn
    return None


def _reflexive_pairs(fn):
    n = 0
    for sub in ast.walk(fn):
        if isinstance(sub, ast.Compare) and len(sub.ops) == 1:
            if isinstance(sub.ops[0], (ast.Eq, ast.Is)):
                if norm(sub.left) == norm(sub.comparators[0]):
                    n += 1
        elif isinstance(sub, ast.Call) and len(sub.args) >= 2 and not sub.keywords:
            f = sub.func
            nm = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", None)
            if nm in SELF_EQUAL_METHODS and norm(sub.args[0]) == norm(sub.args[1]):
                n += 1
    return n


# The trailing `s?` matters: django's test is `test_comparisons`, and without
# it the keyword matched while the plural `s` broke the boundary, so a
# deliberate operator test was reported. Its `Distance.__eq__` compares
# `self.standard == other.standard` with no identity fast path, so `d1 == d1`
# does real work as well (see memory self-equality-needs-a-short-circuit).
# `reflexiv` was in this list from the start and never matched anything: the
# `s?(?:$|_)` tail requires a boundary right after the token, so `reflexivity`
# and even `reflexive` both fell through. climada has two `test_reflexivity`
# methods, each `assertEqual(x, x)` beside a `test_symmetry`, which is textbook
# __eq__ testing and was reported as vacuous. Same shape as the plural bug that
# let `test_comparisons` through. Tokens that take suffixes now allow them.
COMPARISON_TEST = re.compile(
    r'(?:^|_)(?:comparison|compare|equality|equal|eq|ne|hash|hashable'
    r'|identity|reflexiv\w*|symmetr\w*|transitiv\w*|dunder|operator)s?(?:$|_)',
    re.I)

# A SECOND reason `x == x` can be the point, distinct from testing `__eq__`.
# When the operand recomputes, naming it twice produces two independent values
# and comparing them tests that the computation is deterministic. wagtail's
# `test_cache_key_consistent` does exactly this: `cache_key` is a property that
# md5-hashes the page's components on every access, so
# `assertEqual(self.page.cache_key, self.page.cache_key)` asserts the hash is
# stable, and the class around it (`TestPageCacheKey`, with `test_no_queries`
# and `test_changes_when_slug_changes`) confirms the intent.
#
# Property-ness cannot be read from the call site, so the test's own name is
# the signal. Kept separate from COMPARISON_TEST because the two say different
# things: that one means "we are testing equality", this one means "we are
# testing that recomputing agrees".
DETERMINISM_TEST = re.compile(
    r'(?:^|_)(?:consistent|consistency|stable|stability|deterministic|determinism'
    r'|idempotent|idempotency|repeatable|unchanged|cached|cacheable|memoiz\w*'
    r'|same)s?(?:$|_)', re.I)



NAN_HINT = re.compile(r'\b(?:nan|not\s*a\s*number|finite|isnan)\b', re.I)


def nan_check_nearby(lines, lineno):
    """True when this line or the one above mentions NaN or finiteness."""
    for k in (lineno - 1, lineno - 2):
        if 0 <= k < len(lines) and NAN_HINT.search(lines[k]):
            return True
    return False

def names_a_comparison(tree, node):
    """True when the enclosing test's own name is about comparison semantics."""
    fn = enclosing_function(tree, node)
    return bool(fn is not None and (COMPARISON_TEST.search(fn.name)
                                    or DETERMINISM_TEST.search(fn.name)))


def reflexive_count(tree, node):
    """How many reflexive comparisons live in the function containing `node`."""
    fn = enclosing_function(tree, node)
    return _reflexive_pairs(fn) if fn is not None else 0


def is_loop_target(tree, node, left):
    """True when `left` is exactly a for-loop's target name, not an attribute of it."""
    if not isinstance(left, ast.Name):
        return False
    for loop in ast.walk(tree):
        if not isinstance(loop, (ast.For, ast.AsyncFor)):
            continue
        targets = ([loop.target] if isinstance(loop.target, ast.Name)
                   else [t for t in getattr(loop.target, "elts", [])
                         if isinstance(t, ast.Name)])
        if not any(t.id == left.id for t in targets):
            continue
        for sub in ast.walk(loop):
            if sub is node:
                return True
    return False


def in_contract_matrix(tree, node, left):
    """True when the same operand is also compared to something DIFFERENT here.

    That is the shape of an equality or hash contract test, where reflexivity is
    asserted alongside the non-reflexive cases. Suppressing on it costs nothing
    real: a genuinely mistaken self-comparison, like erpnext's
    `assertEqual(schedule.journal_entry, schedule.journal_entry)`, has no
    sibling assertion comparing that same expression to anything else.
    """
    fn = enclosing_function(tree, node)
    if fn is None:
        return False
    key = norm(left)
    for sub in ast.walk(fn):
        if isinstance(sub, ast.Compare) and len(sub.ops) == 1:
            a, b = norm(sub.left), norm(sub.comparators[0])
            if a == key and b != key:
                return True
            if b == key and a != key:
                return True
        elif isinstance(sub, ast.Call) and len(sub.args) >= 2:
            f = sub.func
            nm = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", None)
            if nm in SELF_EQUAL_METHODS or (nm or "").startswith(("assertNotEqual",
                                                                  "assertIsNot")):
                a, b = norm(sub.args[0]), norm(sub.args[1])
                if (a == key) != (b == key):
                    return True
    return False


def scan(path):
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
        if is_generated(text):
            return
        tree = ast.parse(text)
    except (SyntaxError, OSError):
        return
    src_lines = text.splitlines()
    for node in ast.walk(tree):
        left = right = None
        label = None
        is_identity = False
        if isinstance(node, ast.Call) and len(node.args) >= 2 and not node.keywords:
            fn = node.func
            name = fn.attr if isinstance(fn, ast.Attribute) else getattr(fn, "id", None)
            if name in SELF_EQUAL_METHODS:
                left, right, label = node.args[0], node.args[1], name
        elif isinstance(node, ast.Assert) and isinstance(node.test, ast.Compare):
            cmp = node.test
            if len(cmp.ops) == 1 and isinstance(cmp.ops[0], (ast.Eq, ast.Is)):
                left, right, label = cmp.left, cmp.comparators[0], "assert =="
                is_identity = isinstance(cmp.ops[0], ast.Is)
        if left is None or norm(left) != norm(right):
            continue
        # A call on BOTH sides is not a vacuous assertion, it is two separate
        # evaluations that may produce different objects, and comparing them is
        # the whole point. ibis asserts `Scalar() == Scalar()` and
        # `hash(FrozenOrderedDict(a=1, b=2)) == hash(FrozenOrderedDict(a=1, b=2))`
        # to check that independently constructed equal values compare and hash
        # equal, which is exactly what a value type must guarantee. This used to
        # be printed with a SIDE-EFFECT note, so the tool already knew and
        # reported it anyway; 20 of ibis's 39 hits were this.
        if has_call(left):
            continue
        # A bare self-comparison inside an equality CONTRACT matrix is
        # deliberate: for a custom __eq__, `x == x` is not guaranteed and
        # reflexivity is a real property to assert. The signature is that the
        # same function also compares that same operand to something else, as
        # ibis's test_pseudo_hashable does across twelve lines of ph1/ph2/ph3/ph4.
        if in_contract_matrix(tree, node, left):
            continue
        # Reflexivity asserted on a LOOP VARIABLE is the same contract test
        # written as a loop. ibis's test_deferred does
        # `for obj in [a, b, c, d]: assert obj == obj`, where the siblings a, b,
        # c, d are compared elsewhere under their own names, so the matrix check
        # cannot see it. Keyed on the operand BEING the loop target, not merely
        # derived from it, so erpnext's `schedule.journal_entry` inside
        # `for i, schedule in enumerate(...)` is still reported.
        if is_loop_target(tree, node, left):
            continue
        # `x.y is x.y` on an ATTRIBUTE or SUBSCRIPT tests that the access is
        # CACHED. Attribute access can run a property, so two accesses may
        # return different objects, and asserting identity is the only way to
        # pin that they do not. zarr's test_chunk_resolution asserts
        # `table.local is table.local` directly below
        # `assert plan.partition() is partition`, which is the same check
        # written with a call. Restricted to `is`: erpnext's mistakes are
        # `assertEqual`, and an == self-comparison on an attribute is still
        # reported.
        if is_identity and not isinstance(left, ast.Name):
            continue
        # `x == x` on a FLOAT is the standard NaN check, not a tautology: IEEE
        # 754 makes NaN != NaN, so the assertion fails exactly when x is NaN.
        # unsloth writes `assert r0["qat_loss_after"] == r0["qat_loss_after"]`
        # with the comment `# finite, not NaN` on the same line, which is the
        # author saying so. Keyed on a nan/finite mention on that line or the
        # one above, since the operand's type is not visible here.
        if nan_check_nearby(src_lines, node.lineno):
            continue
        # TRIAGE NOTE, not a suppression: `x == x` is only vacuous when the
        # type's `__eq__` short-circuits on `self is other` or is the default.
        # sqlglot's `expr == expr` never hashes for exactly that reason, but
        # pyproj's `datum == datum` calls PROJ and pyiceberg's pydantic models
        # compare __dict__, both with no identity fast path, so both do real
        # work and are legitimate reflexivity checks. Read `__eq__` before
        # filing a reported `==` self-comparison.
        # Three or more reflexive comparisons in ONE function is a deliberate
        # block, not three mistakes. pydantic's test_validate_call asserts
        # `thing.a == thing.a`, `thing.c == thing.c`, `Thing.c == Thing.c` to
        # check that validate_call wrappers compare equal across accesses, and
        # a second cluster there says so outright: "# verify that equality
        # still holds for instance methods". A real mistake comes alone, as
        # erpnext's two do, one per test.
        if reflexive_count(tree, node) >= 3:
            continue
        # A test NAMED for comparison semantics is asserting reflexivity on
        # purpose. msgspec's test_raw_comparison opens with `assert r == r` and
        # `assert not r != r` before covering equal values, different values and
        # memoryview slices. The counting rule misses it because `!=` is
        # excluded and `r` is never compared to anything else, so the name is
        # the only signal left. erpnext's real pair sit in tests named
        # test_depreciation_schedule and test_blanket_order_rate.
        if names_a_comparison(tree, node):
            continue
        note = ""
        try:
            text = ast.unparse(left)
        except Exception:
            text = "<expr>"
        print(f"{path}:{node.lineno}: {label}({text}, {text}) cannot fail{note}")
        STATS["hits"] += 1


# Vendored trees are excluded, not because the analysis fails there but because
# the project has usually written them off. pyinstaller#9567 removed two
# provably dead stubs from tests/unit/test_modulegraph/ and was closed with
# "That stuff's vendored cruft we hope to get rid of."
VENDOR_PARTS = ("/_vendor/", "/vendored/", "/_vendored/", "/externals/",
                "/third_party/", "/thirdparty/", "/bundled/", "/patched/",
                "/vendor/", "/test_modulegraph/")

for root in sys.argv[1:] or ["."]:
    for f in Path(root).rglob("*.py"):
        s = str(f)
        if "/.venv" in s or "/site-packages/" in s or "/node_modules/" in s or "/.pixi/" in s:
            continue
        if any(v in s for v in VENDOR_PARTS):
            continue
        if "/tests/data/" in s or "/test/data/" in s or "/fixtures/" in s:
            continue
        if f.name.startswith("test_") or f.name.endswith("_test.py"):
            STATS["files"] += 1
            scan(f)

print(f'-- {STATS["hits"]} vacuous assertion(s) from {STATS["files"]} '
      f'test file(s)', file=sys.stderr)

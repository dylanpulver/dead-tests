#!/usr/bin/env python3
"""Find Python tests that can never run because a later definition shadows them.

Two `def test_x` at the same level in one module: the second binding wins and
pytest only ever collects one of them. The first is dead code that reads like
coverage. Same for two methods of the same name in one test class.

This is the "test that never runs" cousin of the dead-assertion seam: the bug is
not a wrong assertion, it is an assertion nobody evaluates.

False positives to expect, so every hit still gets read:
  1. A redefinition guarded by `if`/`else` or `try`/`except` (version shims),
     or decorated differently per platform. Reported with a GUARDED note.
  2. A fixture or helper named test_* that is deliberately overridden.
  3. Names defined in different classes, or nested in different functions.
     Excluded here by comparing full scope paths, not bare names.

Usage: find-shadowed-tests.py [path ...]
"""
import ast
import re
import sys
import warnings

# Suppress the SCANNED repository's SyntaxWarnings. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is the subject's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path.
# changedetection.io alone emitted twelve lines of it, which buried this
# scanner's actual result. A scanner must not report its subject's warnings as
# if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)

from pathlib import Path

# A generated file is not a place to find a bug: the defect, if any, is in the
# generator's input, and a PR against the output is rejected on sight. ccxt
# transpiles its Python test suite from TypeScript and every file says
# "PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN",
# which is how 18 candidates there turned out to be unfilable.
GENERATED_BANNER = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')


def is_generated(text):
    """True when the file announces itself as generated, judged on its head."""
    return bool(GENERATED_BANNER.search(text[:4000]))


def scope_defs(node, path, guarded=False):
    """Yield (scope_path, name, lineno, guarded) for defs directly in `node`."""
    for child in getattr(node, "body", []):
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
            yield (path, child.name, child.lineno, guarded)
        elif isinstance(child, ast.ClassDef):
            yield from scope_defs(child, path + (child.name,), guarded)
        elif isinstance(child, (ast.If, ast.Try)):
            # A redefinition inside a conditional is usually a deliberate shim.
            for sub in ast.iter_child_nodes(child):
                if hasattr(sub, "body") or isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    yield from scope_defs(child, path, guarded=True)
                    break


# A scanner that prints nothing on a clean run is indistinguishable from one
# that crashed or discovered no files. This tool printed literally nothing
# across a 34-repo corpus and I could not tell which had happened without
# reading its source. Same family as every other suppressed-diagnostic bug in
# this toolkit: report the denominator, always.
STATS = {"files": 0, "hits": 0}


def scan(p):
    STATS["files"] += 1
    try:
        text = p.read_text(encoding="utf-8", errors="replace")
        if is_generated(text):
            return
        tree = ast.parse(text)
    except (SyntaxError, OSError):
        return
    seen = {}
    for path, name, lineno, guarded in scope_defs(tree, ()):
        key = (path, name)
        if key in seen:
            first_line, first_guarded = seen[key]
            if name.startswith("test") or name.startswith("Test"):
                note = "  GUARDED (likely a deliberate shim)" if (guarded or first_guarded) else ""
                scope = ".".join(path) or "<module>"
                # Ruff/pyflakes F811 reports a module-level redefinition but is
                # blind to a duplicate METHOD inside a class, so a repo can select
                # "F" and still carry class-scope shadowing. Verified 2026-09-27:
                # F811 found all 7 module-level cases in mlflow's test_prompts.py
                # and none of dnspython's class-scope case. Class-scope hits are
                # therefore the durable half of this seam.
                # NOT "F811 blind": ruff 0.0.292, flake8 and pyflakes all
                # report a class-scope redefinition (verified on a two-case
                # fixture). These survive because projects do not ENABLE F811,
                # not because linters cannot see them: DendroPy's lint.sh
                # selects only E9,F63,F7,F82,W605, and turning F811 on there
                # reports 26 across the repo.
                kind = "class-scope" if path else "module-scope"
                print(f"{p}:{lineno}: {scope}.{name} shadows line {first_line}  [{kind}]{note}")
                STATS["hits"] += 1
        seen[key] = (lineno, guarded)


# Vendored trees are excluded, not because the analysis fails there but because
# the project has usually written them off. pyinstaller#9567 removed two
# provably dead stubs from tests/unit/test_modulegraph/ and was closed with
# "That stuff's vendored cruft we hope to get rid of."
VENDOR_PARTS = ("/_vendor/", "/vendored/", "/_vendored/", "/externals/",
                "/third_party/", "/thirdparty/", "/bundled/", "/patched/",
                "/vendor/", "/test_modulegraph/")

for root in sys.argv[1:] or ["."]:
    for f in Path(root).rglob("*.py"):
        s = str(f)
        if "/.venv" in s or "/site-packages/" in s or "/node_modules/" in s:
            continue
        # Only files pytest actually collects. A formatter's fixture corpus
        # (black's tests/data/cases/*.py) and shared helpers living under
        # tests/ are full of repeated `def test`, and none of it ever runs as
        # a test. Matching pytest's own patterns removes both.
        if any(v in s for v in VENDOR_PARTS):
            continue
        if "/tests/data/" in s or "/test/data/" in s or "/fixtures/" in s:
            continue
        if f.name.startswith("test_") or f.name.endswith("_test.py"):
            scan(f)
    print(f'-- {STATS["hits"]} shadowed test(s) from {STATS["files"]} '
          f'test file(s)', file=sys.stderr)

#!/usr/bin/env python3
"""Find minitest methods that are never run.

minitest collects a method only when its name starts with `test_` and it lives
in a `Minitest::Test` subclass (or a framework subclass of one, such as
`ActiveSupport::TestCase`). A method that asserts things but is named
`verifies_the_thing` is silently dead: no error, no skip, no mention in the
output. The Ruby twin of the PHP and Java seams, and it exists for the same
reason, the convention is a prefix a human types rather than something the
toolchain checks.

RSpec is deliberately out of scope: its `it` blocks are registered by the call
itself, so this shape cannot occur there.

A method is reported only when all of these hold, which is what keeps the
false-positive rate low enough to act on:

  * the file looks like a test file and declares a test-case subclass
  * the method is not named `test_*` and is not a known hook
  * its body contains an assertion
  * nothing anywhere else in the tree mentions the name, so it is not a helper
    shared with a sibling file, which is how craftcms and ccxt produced dozens
    of false hits in the PHP and Python versions of this tool
  * the class does not `skip` unconditionally in `setup`, because collecting a
    method there would change nothing

A regression fixture lives at `cases/rbfix`, which encodes one
true positive plus the four false-positive shapes (cross-file helper, in-file
helper, parked `disabled_` prefix, framework hook). It should report exactly
one hit. It cannot live under a `tmp` directory, because `tmp` is in SKIP_DIRS.

PREVALENCE WARNING, measured 2026-10-31 over 12 fresh Ruby repos: **1,327
`*_spec.rb` files against 7 minitest classes**. Open-source Ruby is
overwhelmingly RSpec, where an example is registered by the `it` call itself,
so this shape cannot occur. This tool is correct and cheap to run, but the
population it applies to is small; do not expect PHP-like yield.

Usage: find-uncollected-ruby-tests.py <path>...
"""
import re
import sys
from pathlib import Path

# A generated file is not a place to find a bug: the defect would be in the
# generator's input, and a PR against the output is rejected on sight.
GENERATED_BANNER = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')

# `class FooTest < Minitest::Test`, `< ActiveSupport::TestCase`, `< TestCase`,
# and the Test::Unit spelling. Anything ending in TestCase counts, which is how
# project-local base classes (`class FooTest < ApplicationTestCase`) are caught.
CLASS_DECL = re.compile(
    r'^[ \t]*class\s+(\w+)\s*<\s*([\w:]+)', re.M)
TEST_BASE = re.compile(r'(?:^|::)(?:Test|TestCase|MiniTest|Minitest)$|TestCase$')

METHOD_DECL = re.compile(r'^([ \t]*)def\s+(?:self\.)?([a-zA-Z_]\w*[?!]?)', re.M)

ASSERTION = re.compile(
    r'\b(assert\w*|refute\w*|flunk|must_\w+|wont_\w+|'
    r'assert_response|assert_difference|assert_no_difference)\b')

# minitest and Rails call these themselves.
HOOKS = re.compile(
    r'^(setup|teardown|before_setup|after_setup|before_teardown|after_teardown|'
    r'setup_fixtures|teardown_fixtures|default_test|initialize|'
    r'method_missing|respond_to_missing\?)$')

# A deliberately parked method, named so on purpose.
PARKED_PREFIX = ('disabled_', 'disable_', 'skip_', 'skipped_', 'xtest',
                 'ignore_', 'pending_', 'broken_')

SKIP_DIRS = {'.git', 'vendor', 'node_modules', 'tmp', 'log', 'coverage',
             'fixtures', 'generated', '.bundle'}


def interesting_files(roots):
    for root in roots:
        for f in Path(root).rglob('*.rb'):
            if SKIP_DIRS & set(f.parts):
                continue
            yield f


def is_test_file(path):
    n = path.name
    return n.endswith('_test.rb') or n.startswith('test_') or n.endswith('_spec.rb')


def reference_map(roots):
    """name -> set of .rb files mentioning it, for the cross-file helper check.

    An own-file count cannot distinguish a shared helper from an uncollected
    test, because a helper's callers are in other files by definition.
    """
    refs = {}
    for f in interesting_files(roots):
        try:
            text = f.read_text(errors='replace')
        except OSError:
            continue
        for m in re.finditer(r'\b([a-zA-Z_]\w*[?!]?)\b', text):
            refs.setdefault(m.group(1), set()).add(f)
    return refs


def body_of(text, start, indent):
    """The method body, by indentation: Ruby `end` matching needs a parser."""
    lines = text[start:].split('\n')
    out = [lines[0]]
    for line in lines[1:]:
        if line.strip() and not line.startswith(indent + ' ') \
                and not line.startswith(indent + '\t'):
            if line.strip() == 'end' or line.startswith(indent + 'end'):
                break
            if re.match(r'^[ \t]*(def|class|module|private|protected)\b', line):
                break
        out.append(line)
    return '\n'.join(out)


def declares_test_case(text):
    for m in CLASS_DECL.finditer(text):
        if TEST_BASE.search(m.group(2)):
            return True
    return False


def setup_always_skips(text):
    """True when `setup` calls `skip` with no conditional around it."""
    m = re.search(r'^[ \t]*def\s+setup\b', text, re.M)
    if not m:
        return False
    body = body_of(text, m.start(), '')
    if not re.search(r'^\s*skip\b', body, re.M):
        return False
    head = body[:re.search(r'^\s*skip\b', body, re.M).start()]
    return not re.search(r'\b(if|unless|case|while)\b', head)


def scan(roots):
    hits, examined = [], 0
    refs = reference_map(roots)
    for f in interesting_files(roots):
        if not is_test_file(f):
            continue
        try:
            text = f.read_text(errors='replace')
        except OSError:
            continue
        if GENERATED_BANNER.search(text[:4000]):
            continue
        if not declares_test_case(text):
            continue
        examined += 1
        if setup_always_skips(text):
            continue
        for m in METHOD_DECL.finditer(text):
            indent, name = m.group(1), m.group(2)
            if name.startswith('test_') or HOOKS.match(name):
                continue
            if name.startswith(PARKED_PREFIX):
                continue
            if name.startswith('_'):
                continue
            body = body_of(text, m.start(), indent)
            if not ASSERTION.search(body):
                continue
            # Mentioned in any other file? Then it is a shared helper.
            where = refs.get(name, set())
            if len(where - {f}) > 0:
                continue
            # Or called elsewhere in this file.
            if len(re.findall(r'\b' + re.escape(name) + r'\b', text)) > 1:
                continue
            line = text[:m.start()].count('\n') + 1
            hits.append(f'{f}:{line}: {name}')
    return hits, examined


def main():
    roots = [a for a in sys.argv[1:] if not a.startswith('--')] or ['.']
    hits, examined = scan(roots)
    print('\n'.join(hits))
    print(f'-- {len(hits)} candidate(s) from {examined} test-case file(s)',
          file=sys.stderr)


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Find assertions that can never run because they sit inside a `pytest.raises`
block after the statement that raises.

    with pytest.raises(Foo):
        do_the_thing()          # raises here
        assert x == y           # never reached

Found by hand in redis-py (`test_lock_error_gives_correct_lock_name`, 2026-09-10),
where deleting the behaviour under test left the suite green. The pattern is
mechanical, so it is worth scanning for rather than stumbling over.

Reports only blocks with 2+ statements where a later statement is an assert,
since a single-statement block is the correct idiom.

THIS IS A LEAD GENERATOR, NOT AN ORACLE. Read every hit. Four false-positive
classes seen in real code, and the last one is the important one:

  1. The block ends with an explicit `raise` ("set up, assert, then raise"), so
     the earlier assertions do run. Excluded automatically below.
  2. The assertion IS the raiser: `with pytest.raises(AttributeError): ...;
     assert self.x` where reading self.x is what raises (pydantic
     test_edge_cases.py). Not detectable syntactically.
  3. The whole test is `@pytest.mark.xfail(strict=True)` and documents a known
     break (fsspec test_multilevel_chained_fs). Cleaning it is churn.
  4. **The assertion guards the did-not-raise path on purpose.** If it asserts
     on a RESULT computed inside the block rather than on the exception, it is
     often deliberate: it only runs when the call failed to raise, and an
     AssertionError is not caught by `pytest.raises(SomeOtherError)`, so the
     test still fails correctly. nltk's traversal and XXE tests and pydantic's
     `assert False, "... should not be importable"` are all this shape.

The rule that separates them: **what does the assertion talk about?**
  - It asserts on the EXCEPTION (`e`, `e.value`, `excinfo.value`) -> genuinely
    dead. The exception object is only meaningfully available after the block,
    so an assertion on it inside the block can never be doing its job.
  - It asserts on a RESULT or a mock -> read it. It may be an intentional guard
    for the non-raising path, or a real post-condition that belongs after the
    block. Running it after moving it out is what settles the question.

Usage: find-dead-assertions.py <path> [path ...]
"""
import ast
import re
import sys
import warnings

# Suppress the SCANNED repository's SyntaxWarnings. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is the subject's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path.
# changedetection.io alone emitted twelve lines of it, which buried this
# scanner's actual result. A scanner must not report its subject's warnings as
# if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)

from pathlib import Path

# A generated file is not a place to find a bug: the defect, if any, is in the
# generator's input, and a PR against the output is rejected on sight. ccxt
# transpiles its Python test suite from TypeScript and every file says
# "PLEASE DO NOT EDIT THIS FILE, IT IS GENERATED AND WILL BE OVERWRITTEN",
# which is how 18 candidates there turned out to be unfilable.
GENERATED_BANNER = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')


def is_generated(text):
    """True when the file announces itself as generated, judged on its head."""
    return bool(GENERATED_BANNER.search(text[:4000]))


def is_raises(node: ast.withitem) -> bool:
    call = node.context_expr
    if not isinstance(call, ast.Call):
        return False
    f = call.func
    name = ""
    if isinstance(f, ast.Attribute):
        name = f.attr
        if isinstance(f.value, ast.Name):
            name = f"{f.value.id}.{f.attr}"
    elif isinstance(f, ast.Name):
        name = f.id
    return name.endswith("raises") or name.endswith("RaisesExc") or name.endswith("raises_group")


def scan(path: Path) -> list[tuple[int, int, str]]:
    try:
        text = path.read_text(encoding="utf-8")
        if is_generated(text):
            return []
        tree = ast.parse(text)
    except (SyntaxError, UnicodeDecodeError):
        return []
    hits = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.With, ast.AsyncWith)):
            continue
        if not any(is_raises(i) for i in node.items):
            continue
        body = node.body
        if len(body) < 2:
            continue
        # Everything after the first statement is unreachable IF the first raises.
        # It often does not: a block that ends with an explicit `raise` is the
        # "set up, assert, then raise" shape, where the asserts genuinely run.
        # poetry's test_indicator_context_resets_on_exception is exactly that
        # (2026-09-10), so an explicit raise later in the block clears the block.
        for i, stmt in enumerate(body[1:], start=1):
            if not isinstance(stmt, ast.Assert):
                continue
            if any(isinstance(later, ast.Raise) for later in body[i + 1:]):
                continue
            hits.append((node.lineno, stmt.lineno, ast.unparse(stmt)[:90]))
    return hits


SKIP = {".venv", "venv", "site-packages", "node_modules", ".git", "build", ".tox", ".mypy_cache"}

total = 0
FILES = 0
for root in sys.argv[1:]:
    for f in sorted(Path(root).rglob("*.py")):
        # Vendored dependencies are not this repo's code and drown the signal.
        if SKIP & set(f.parts):
            continue
        FILES += 1
        for with_line, assert_line, src in scan(f):
            print(f"{f}:{assert_line}  (inside pytest.raises opened at line {with_line})")
            print(f"    {src}")
            total += 1
print(f"\n{total} unreachable assertion(s) from {FILES} python file(s)",
      file=sys.stderr)

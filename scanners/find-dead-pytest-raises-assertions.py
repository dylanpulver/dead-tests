#!/usr/bin/env python3
"""Find assertions inside `with pytest.raises(...)` that can never verify anything.

THE PROOF, which is what makes this different from the other dead-assertion
scanners. For the test to pass, the body of `with pytest.raises(E)` must raise
`E`. A bare `assert`, and an `assert*()` helper, can only raise AssertionError
on a false condition. So when `E` cannot be AssertionError and the assertion is
the LAST statement of a body with two or more statements, the assertion never
completes as an assertion: either an earlier statement raised, or the
assertion's own expression raised. Either way it has never checked anything,
and the coverage it looks like it provides does not exist.

This is the Python twin of the shape filed as api-platform/core#8772, where six
`assertEquals` sat below the throwing call inside PHPUnit's `expectException`
and were the only coverage of a whole code path.

WHAT IS DELIBERATELY NOT REPORTED, because it is not provable:

  with pytest.raises(TypeError):
      coerce(None)
      assert coerce(1) == 1     # may genuinely run
      cleanup()                 # ... because THIS might be the raiser

A middle assertion is dead only if the statement before it is the raiser, and
nothing in the syntax says which statement raises. Requiring the assertion to be
last is what makes every candidate raiser precede it. Reporting the weaker shape
would hand back a triage queue, which is the cost the PHP scanner paid 54 false
positives to learn.

Also excluded: `E` that could BE AssertionError (AssertionError itself,
Exception, BaseException, or a tuple containing one), a body of a single
statement (the assertion is then the raiser, which is a legitimate way to write
`pytest.raises(AssertionError)`), an `E` we cannot resolve to an exception class,
and `pytest.warns` / `deprecated_call`, which do NOT stop execution, so code
after the warning call runs normally.

Fixture: cases/pyraises, 9 cases, exactly 2 expected hits, with
the expected answer written down before the first run.

Usage: find-dead-pytest-raises-assertions.py <path>...
"""
import ast
import re
import sys
import warnings

# Suppress the SCANNED repository's SyntaxWarnings. A line reading
# `<unknown>:1762: SyntaxWarning: invalid escape sequence` is the subject's own
# string literal, surfaced because ast.parse compiles it; `<unknown>` is the
# giveaway, since a warning from this file would carry this path.
# changedetection.io alone emitted twelve lines of it, which buried this
# scanner's actual result. A scanner must not report its subject's warnings as
# if they were its own.
warnings.filterwarnings('ignore', category=SyntaxWarning)

import warnings
from pathlib import Path

# Parsing other projects' sources emits their SyntaxWarnings on OUR stderr, which
# buried this tool's own `-- N hit(s) from M files` line in a 401-repo run. The
# denominator is the part that proves the walk was not short, so keep it readable.
warnings.simplefilter('ignore', SyntaxWarning)

# `.pixi` and friends hold INSTALLED third-party packages, whose test files are
# not this repo's code. A pyjanitor scan reported 3 hits inside a vendored
# jupyter_server under `.pixi/envs/default/etc/conda/test-files/`.
SKIP_DIRS = {'.git', 'node_modules', '.tox', '.venv', 'venv', 'build', 'dist',
             '.mypy_cache', '.pytest_cache', 'site-packages', '.eggs',
             '.pixi', '.conda', 'conda-meta', 'test-files', '.hatch',
             'node_modules', '__pypackages__', '.nox'}

# A generated file is not a place to find a bug: the defect is in the generator.
GENERATED = re.compile(
    r'(?i)\b(do not (?:edit|modify)|autogenerated|auto-generated'
    r'|automatically generated|generated by|@generated)\b')

# Anything that could catch an AssertionError makes the proof fail.
CATCHES_ASSERTION = {'AssertionError', 'Exception', 'BaseException'}

# Conservative: only treat a name as a known exception CLASS when it looks like
# one. `pytest.raises(exc)` and `pytest.raises(self.err)` are unresolvable, and
# an unresolvable E cannot be shown not to be AssertionError.
EXC_NAME = re.compile(r'^[A-Z]\w*(Error|Exception|Exit|Interrupt|Warning|'
                      r'Timeout|Failure|Abort|Invalid|NotFound|Denied)\w*$')
EXTRA_EXC = {'OSError', 'IOError', 'EOFError', 'StopIteration',
             'KeyboardInterrupt', 'SystemExit', 'GeneratorExit'}

RAISES_FUNCS = {'raises', 'assertRaises', 'assertRaisesRegex',
                'assertRaisesRegexp'}
# These do not stop execution, so nothing after them is dead.
NOT_RAISES = {'warns', 'deprecated_call', 'assertWarns', 'assertWarnsRegex'}


PRAGMA_NOCOVER = re.compile(r'#\s*pragma:\s*no\s?cover', re.I)

# An assert that exists only to REFERENCE a name, so a linter does not flag an
# unused local, is the author's mechanism and not a defect. dagster writes it
# three times in test_graph_asset_cannot_use_key_prefix_name_and_key:
#     @graph_asset(key_prefix="a_prefix", key=dg.AssetKey("my_graph_asset"))
#     def _specified_elsewhere() -> int: ...
#     assert _specified_elsewhere  # appease linter
# Measured at only 3 instances in 363,523 python files, so this is suppressed to
# avoid re-triaging the same file every sweep, not because the class is large.
# Counted rather than silent, so a growing class stays visible.
# Deliberately narrow. A broader arm matching any comment containing "unused"
# matched ZERO lines in the 363,523-file corpus, so it was removed rather than
# kept as unvalidated breadth.
LINT_APPEASE = re.compile(
    r'#.*\b(appease|silence|satisfy)\b.*\b(lint\w*|flake\w*|ruff)\b', re.I)
SUPPRESSED = {'lint_appease': 0}


def func_name(node):
    """Dotted tail of a call target: pytest.raises -> 'raises'."""
    f = node.func
    if isinstance(f, ast.Attribute):
        return f.attr
    return getattr(f, 'id', '')


def is_raises_cm(node):
    if not isinstance(node, ast.Call):
        return False
    name = func_name(node)
    if name in NOT_RAISES:
        return False
    return name in RAISES_FUNCS


def exc_names(arg):
    """The exception class names named by E, or None when unresolvable."""
    if isinstance(arg, ast.Name):
        names = [arg.id]
    elif isinstance(arg, ast.Attribute):
        names = [arg.attr]
    elif isinstance(arg, (ast.Tuple, ast.List)):
        out = []
        for el in arg.elts:
            sub = exc_names(el)
            if sub is None:
                return None
            out += sub
        return out
    else:
        return None
    for n in names:
        if not (EXC_NAME.match(n) or n in EXTRA_EXC or n in CATCHES_ASSERTION):
            return None
    return names


def assertion_label(stmt):
    """Non-None when the statement is an assertion that can only raise AssertionError."""
    if isinstance(stmt, ast.Assert):
        return 'assert'
    if isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call):
        n = func_name(stmt.value)
        # `fail(msg)` is EXCLUDED, and the original proof was wrong about it.
        # It is reached exactly when the body does NOT raise, and `Failed` is
        # not the expected type, so it propagates and the test fails WITH the
        # message. pymc's pymc/testing.py and plotly/dash both use it that way
        # on purpose: a better report than a bare "DID NOT RAISE".
        # `failUnless` / `failIf` stay, since those are real unittest asserts.
        if n == 'fail':
            return None
        if n.startswith(('assert', 'failUnless', 'failIf')):
            return n + '()'
    return None


def is_xfail(node):
    """True when the test is marked xfail, so its own failure is the point.

    An xfail test documents a bug. fsspec's test_multilevel_chained_fs carries
    `@pytest.mark.xfail(reason="see issue #334", strict=True)` and reproduces
    the broken chained-filesystem syntax, with a comment reading "We expected
    this to be the correct syntax". Whether an assertion inside its
    `pytest.raises` block is reachable is beside the point: the test exists to
    fail, and tidying it would meddle with a deliberate reproduction.
    """
    for dec in getattr(node, 'decorator_list', []):
        probe = dec.func if isinstance(dec, ast.Call) else dec
        parts = []
        while isinstance(probe, ast.Attribute):
            parts.append(probe.attr)
            probe = probe.value
        if isinstance(probe, ast.Name):
            parts.append(probe.id)
        if 'xfail' in parts:
            return True
    return False


def enclosing_test(tree):
    """line -> test function name, for reporting. xfail tests map to None."""
    owner = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            end = getattr(node, 'end_lineno', node.lineno)
            name = None if is_xfail(node) else node.name
            for ln in range(node.lineno, end + 1):
                owner.setdefault(ln, name)
    return owner


def scan_file(path):
    try:
        src = path.read_text(errors='replace')
    except OSError:
        return []
    if GENERATED.search(src[:4000]):
        return []
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return []
    src_lines = src.splitlines()
    owner = enclosing_test(tree)
    hits = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.With, ast.AsyncWith)):
            continue
        cms = [i.context_expr for i in node.items if is_raises_cm(i.context_expr)]
        if not cms:
            continue
        cm = cms[0]
        if not cm.args:
            continue
        names = exc_names(cm.args[0])
        if names is None:
            continue
        if any(n in CATCHES_ASSERTION for n in names):
            continue
        body = node.body
        if len(body) < 2:
            continue
        label = assertion_label(body[-1])
        if label is None:
            continue
        ln = body[-1].lineno
        # `# pragma: no cover` ON the assertion is the author stating that the
        # line never runs, which is the mechanism, not the defect. ansible's
        # test_subclass_dispatch_collision writes
        #     class _OopsConflicting...(...): ...
        #     assert _OopsConflicting...  # pragma: nocover
        # inside the raises block, where the assert exists only to reference
        # the class so nothing flags an unused local.
        if 0 < ln <= len(src_lines) and PRAGMA_NOCOVER.search(src_lines[ln - 1]):
            continue
        if 0 < ln <= len(src_lines) and LINT_APPEASE.search(src_lines[ln - 1]):
            SUPPRESSED['lint_appease'] += 1
            continue
        # An xfail test maps to None: its own failure is the point, so the
        # reachability of an assertion inside it is not a defect.
        name = owner.get(ln, "?")
        if name is None:
            continue
        hits.append(f'{path}:{ln}: {name}: '
                    f'{label} after {func_name(cm)}({"/".join(names)})')
    return hits


def main():
    roots = [a for a in sys.argv[1:] if not a.startswith('--')] or ['.']
    hits, nfiles = [], 0
    for root in roots:
        for f in Path(root).rglob('*.py'):
            if SKIP_DIRS & set(f.parts):
                continue
            nfiles += 1
            hits += scan_file(f)
    print('\n'.join(hits))
    note = (f", {SUPPRESSED['lint_appease']} suppressed as linter appeasement"
            if SUPPRESSED['lint_appease'] else '')
    print(f'-- {len(hits)} provable hit(s) from {nfiles} python file(s){note}',
          file=sys.stderr)


if __name__ == '__main__':
    main()
